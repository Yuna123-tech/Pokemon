// 먹이그물에서 쓰는 이름 (상수리나무 → 도토리)
function webName(id) { return (WEB_NODES[id] && WEB_NODES[id].label) || CREATURES[id].name; }

function generatedQuestions() {
  const out = [];
  const textbookIds = ['oak', 'squirrel', 'bulbul', 'snake', 'frog', 'beetle', 'mole', 'mushroom', 'mold',
    'waterweed', 'duck', 'heron', 'snail', 'gull', 'dolphin', 'turtle', 'jelly', 'coral', 'crab', 'ray', 'mackerel', 'seaweed',
    'sun', 'water', 'air', 'soil'];
  // 생물 요소 / 비생물 요소
  textbookIds.forEach(id => {
    const c = CREATURES[id];
    out.push({ topic: 1, type: 'mcq', q: `<b>${c.name}</b>${josa(c.name, '은/는').slice(c.name.length)} 생물 요소일까요, 비생물 요소일까요?`,
      choices: ['🌱 생물 요소', '🪨 비생물 요소'], answer: c.living ? '🌱 생물 요소' : '🪨 비생물 요소',
      explain: `${c.name}${josa(c.name, '은/는').slice(c.name.length)} ${c.living ? '살아 있는 <b>생물 요소</b>' : '살아 있지 않은 <b>비생물 요소</b>'}예요.`,
      subject: { creature: id } });
  });
  // 생산자 / 소비자 / 분해자 (교과서에 나온 생물)
  ['oak', 'squirrel', 'bulbul', 'tit', 'snake', 'frog', 'mushroom', 'mold', 'grass', 'clover', 'cornel', 'grasshopper',
    'caterpillar', 'rabbit', 'weasel', 'hawk', 'waterweed', 'duck', 'seaweed', 'turtle'].forEach(id => {
    const c = CREATURES[id]; const r = ROLE_INFO[c.role];
    out.push({ topic: 2, type: 'mcq', q: `<b>${c.name}</b>${josa(c.name, '은/는').slice(c.name.length)} 생태계에서 어떤 역할을 할까요?`,
      choices: ['🌿 생산자', '🍽️ 소비자', '🍄 분해자'], answer: `${r.icon} ${r.label}`,
      explain: `${c.name}: <b>${r.label}</b> — ${r.desc}`, subject: { creature: id } });
  });
  // 먹이 관계 (교과서에 나온 관계만)
  const ids = [...new Set(TEXTBOOK_EDGES.flat())];
  ids.forEach(id => {
    const eaters = TEXTBOOK_EDGES.filter(e => e[0] === id).map(e => e[1]);
    const foods = TEXTBOOK_EDGES.filter(e => e[1] === id).map(e => e[0]);
    // 오답 보기는 게임 속 먹이그물(WEB_EDGES)에서도 관계가 없는 생물만 써요
    const linked = new Set(TEXTBOOK_EDGES.concat(WEB_EDGES).filter(e => e.includes(id)).flat());
    const unrelated = ids.filter(x => x !== id && !linked.has(x));
    const c = { name: webName(id) };
    if (eaters.length) {
      const ans = webName(pick(eaters));
      const wrongs = shuffle(unrelated.filter(x => CREATURES[x].role !== 'producer')).slice(0, 2).map(webName);
      if (wrongs.length === 2)
        out.push(QM(3, `교과서 먹이그물에서 <b>${josa(c.name, '을/를')}</b> 먹는 생물은?`, ans, wrongs,
          `${josa(c.name, '은/는')} ${eaters.map(webName).join(', ')}에게 먹혀요.`, { creature: id }));
    }
    if (foods.length) {
      const ans = webName(pick(foods));
      const wrongs = shuffle(unrelated).slice(0, 2).map(webName);
      if (wrongs.length === 2)
        out.push(QM(3, `교과서 먹이그물에서 <b>${josa(c.name, '이/가')}</b> 먹는 먹이는?`, ans, wrongs,
          `${josa(c.name, '은/는')} ${foods.map(webName).join(', ')}${josa(foods.map(webName).slice(-1)[0], '을/를').slice(-1)} 먹어요.`, { creature: id }));
    }
  });
  // 환경오염 원인 분류
  POLLUTION_CASES.forEach(pc => {
    const mon = POLLUTION_MONSTERS[pc.type];
    out.push({ topic: 4, type: 'mcq', q: `<b>${pc.title}</b>${josa(pc.title, '은/는').slice(pc.title.length)} 어떤 환경오염의 원인일까요?`,
      choices: ['🌫️ 대기오염', '💧 수질오염', '🟫 토양오염'], answer: `${mon.icon} ${mon.label}`,
      explain: `<b>${mon.label}</b> — ${pc.explain}`, subject: { poke: mon.poke, emoji: pc.icon } });
  });
  // 생태계 보전 행동
  ACTIONS.forEach(a => out.push(QX(5, `“${a.text}” 이 행동은 생태계 보전에 도움이 된다.`, a.good, a.explain, { emoji: a.icon })));
  return out;
}

/* ---------- 문제 꺼내기 ----------
   getQuestions({ topics: [1,2], count: 10, types: ['mcq','ox'] }) */
function getQuestions({ topics = [1, 2, 3, 4, 5], count = 10, types = null } = {}) {
  let pool = AUTHORED_QUESTIONS.concat(generatedQuestions()).filter(q => topics.includes(q.topic));
  if (types) pool = pool.filter(q => types.includes(q.type));
  pool = shuffle(pool);
  const out = [];
  while (out.length < count && pool.length) out.push(...pool.splice(0, count - out.length));
  // 문제 수가 모자라면 다시 섞어서 채워요
  while (out.length < count) out.push(...shuffle(out).slice(0, count - out.length));
  return out.map(q => Object.assign({}, q, { choices: q.shuffle ? shuffle(q.choices) : q.choices.slice() }));
}
function questionCount(topics) {
  return AUTHORED_QUESTIONS.concat(generatedQuestions()).filter(q => topics.includes(q.topic)).length;
}
